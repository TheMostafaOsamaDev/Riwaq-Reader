package com.leaflet.reader

import android.app.Activity
import android.content.Intent
import android.os.Bundle
import android.util.Log
import android.view.ActionMode
import android.view.Window
import androidx.activity.enableEdgeToEdge
import androidx.core.view.WindowInsetsControllerCompat

class MainActivity : TauriActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        enableEdgeToEdge()
        super.onCreate(savedInstanceState)
        // Suppress Android's floating text-selection toolbar
        // ("Copy / Select all / Share / Manage apps") so the app's
        // in-page SelectionPopover is the only UI shown when the
        // user highlights text. Selection itself still works — only
        // the system bar is hidden.
        //
        // We wrap the window's existing Window.Callback (delegating
        // every method via Kotlin `by`) and return null for floating
        // ActionMode requests. This intercepts the WebView's request
        // at the window level, which is the durable spot — the
        // generated RustWebView.kt would be a more direct override
        // point but it is regenerated by `tauri android dev`.
        window.callback = SuppressFloatingActionModeCallback(window.callback)
        Log.d("LeafletSheet", "installed SuppressFloatingActionModeCallback in onCreate")

        // Cold launch: stash any intent extra so consume_launch_intent
        // can drain it on frontend mount.
        intent?.let { rememberLaunchIntent(it) }
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        // Warm launch (singleTask): the running activity gets a new
        // intent (e.g., user tapped the notification while the app
        // was backgrounded). Update the stashed value so the frontend's
        // event listener fires the right side effect.
        rememberLaunchIntent(intent)
    }

    override fun onResume() {
        super.onResume()
        // Defensive: if anything in TauriActivity (or a plugin) reset
        // window.callback after onCreate, re-wrap it now so the
        // floating-action-mode suppression survives.
        if (window.callback !is SuppressFloatingActionModeCallback) {
            window.callback = SuppressFloatingActionModeCallback(window.callback)
        }
    }

    private fun rememberLaunchIntent(intent: Intent) {
        val extra = intent.getStringExtra("leaflet.open") ?: return
        pendingLaunchIntent = extra
    }

    companion object {
        /** Stashed launch-intent extra. Drained by Rust's
         *  consume_launch_intent. `@JvmField` emits a true static
         *  field (which JNI `GetStaticFieldID` expects); `@JvmStatic`
         *  would only generate accessor methods, not the field.
         *  `@Volatile` makes cross-thread reads see the latest write. */
        @JvmField
        @Volatile
        var pendingLaunchIntent: String? = null

        /** Set the status- and navigation-bar icon appearance to match
         *  the in-app reading theme, which is independent of the OS
         *  DayNight setting. `lightIcons` = true paints light (white)
         *  icons for a dark background; false paints dark icons for a
         *  light background. Called via JNI from Rust's
         *  set_status_bar_style command on every theme change.
         *
         *  Must touch the window on the UI thread — JNI calls arrive on
         *  an attached Rust thread, so we hop via runOnUiThread.
         *
         *  `@JvmStatic` so JNI sees a static method with a stable
         *  signature: (Landroid/app/Activity;Z)V. */
        @JvmStatic
        fun setBarAppearance(activity: Activity, lightIcons: Boolean) {
            activity.runOnUiThread {
                val window = activity.window
                val controller =
                    WindowInsetsControllerCompat(window, window.decorView)
                // isAppearance*Light* = true means "light background →
                // dark icons", which is the inverse of our lightIcons
                // (= light icons for a dark background) flag.
                controller.isAppearanceLightStatusBars = !lightIcons
                controller.isAppearanceLightNavigationBars = !lightIcons
            }
        }
    }
}

/** Delegates every Window.Callback method to the wrapped instance,
 *  except `onWindowStartingActionMode` for floating ActionModes
 *  (Android's text-selection toolbar) which is short-circuited to
 *  null. Kotlin's `by delegate` forwards the ~25 methods of the
 *  Window.Callback interface so we don't have to spell them all
 *  out individually. */
private class SuppressFloatingActionModeCallback(
    private val delegate: Window.Callback,
) : Window.Callback by delegate {
    override fun onWindowStartingActionMode(
        callback: ActionMode.Callback?,
    ): ActionMode? {
        Log.d("LeafletSheet", "onWindowStartingActionMode (1-arg) — suppressing")
        return null
    }

    override fun onWindowStartingActionMode(
        callback: ActionMode.Callback?,
        type: Int,
    ): ActionMode? {
        Log.d(
            "LeafletSheet",
            "onWindowStartingActionMode (2-arg) type=$type — ${if (type == ActionMode.TYPE_FLOATING) "suppressing" else "passing through"}",
        )
        if (type == ActionMode.TYPE_FLOATING) return null
        return delegate.onWindowStartingActionMode(callback, type)
    }
}
